const sourceIndex = Object.fromEntries(quizSources.map((source) => [source.id, source]))

const getSource = (sourceId) => {
  const source = sourceIndex[sourceId]
  if (!source) throw new Error(`Unknown quiz source: ${sourceId}`)
  const { institution, title, url, accessedAt } = source
  return { institution, title, url, accessedAt }
}

const buildCategory = (prefix, category, entries) => entries.map((entry, index) => {
  const [difficulty, question, options, answer, explanation, sourceId] = entry
  // 依据题号稳定轮换选项，避免正确答案长期固定在同一位置。
  const rotation = (index + prefix.length) % options.length
  const rotatedOptions = [...options.slice(rotation), ...options.slice(0, rotation)]
  const rotatedAnswer = (answer - rotation + options.length) % options.length
  return {
    id: `${prefix}-${String(index + 1).padStart(3, '0')}`,
    category,
    difficulty,
    question,
    options: rotatedOptions,
    answer: rotatedAnswer,
    explanation,
    source: getSource(sourceId),
    verified: true,
  }
})

